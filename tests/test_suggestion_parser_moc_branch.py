def test_enumerate_returns_only_ticked_clusters() -> None:
    """3 MOC blocks: MOC01 [x] Accept, MOC02 [ ] Accept, MOC03 [x] Accept.

    enumerate_moc_sections_split must return:
      ticked   = [MOC01, MOC03]
      unticked = [MOC02]
    """
    report = _empty_report()
    report["candidates"] = [_candidate(f"note-{i}") for i in range(4)]
    report["topic_clusters"] = [
        _cluster("MOC01", title="Ticked One (MOC)", confidence=0.80,
                 candidate_stems=["note-0", "note-1"], slug="ticked-one-moc"),
        _cluster("MOC02", title="Unticked Two (MOC)", confidence=0.65,
                 candidate_stems=["note-2"], slug="unticked-two-moc"),
        _cluster("MOC03", title="Ticked Three (MOC)", confidence=0.50,
                 candidate_stems=["note-3"], slug="ticked-three-moc"),
    ]
    report["parent_options_per_cluster"] = {}

    _filename, body = render_moc_proposal_doc(report, _Cfg())

    # Tick MOC01 and MOC03 (1st and 3rd occurrence of "- [ ] Accept")
    # The rendered body has clusters sorted by confidence DESC: MOC01 (0.80), MOC02 (0.65), MOC03 (0.50)
    # We need to tick the 1st and 3rd "- [ ] Accept"
    parts = body.split("- [ ] Accept")
    assert len(parts) == 4, f"Expected 3 clusters (4 parts after split), got {len(parts)}"
    # Rebuild: tick positions 0 and 2 (MOC01 and MOC03)
    body_modified = (
        parts[0] + "- [x] Accept" +
        parts[1] + "- [ ] Accept" +
        parts[2] + "- [x] Accept" +
        parts[3]
    )

    ticked, unticked = enumerate_moc_sections_split(body_modified)

    ticked_ids = [c["moc_id"] for c in ticked]
    unticked_ids = [c["moc_id"] for c in unticked]

    assert len(ticked) == 2, f"Expected 2 ticked clusters, got {len(ticked)}: {ticked_ids}"
    assert len(unticked) == 1, f"Expected 1 unticked cluster, got {len(unticked)}: {unticked_ids}"
    assert "MOC01" in ticked_ids, f"MOC01 should be ticked; ticked={ticked_ids}"
    assert "MOC03" in ticked_ids, f"MOC03 should be ticked; ticked={ticked_ids}"
    assert "MOC02" in unticked_ids, f"MOC02 should be unticked; unticked={unticked_ids}"


def test_child_wikilinks_extracted_per_cluster() -> None:
    """Ticked cluster dict has 'children' key with all child wikilinks extracted."""
    report = _empty_report()
    report["candidates"] = [_candidate(f"child-{i}") for i in range(5)]
    report["topic_clusters"] = [
        _cluster(
            "MOC01",
            title="Children Extraction (MOC)",
            confidence=0.75,
            candidate_stems=[f"child-{i}" for i in range(5)],
            slug="children-extraction-moc",
        )
    ]
    report["parent_options_per_cluster"] = {}

    _filename, body = render_moc_proposal_doc(report, _Cfg())

    # Tick the single Accept
    body_accepted = body.replace("- [ ] Accept", "- [x] Accept", 1)

    ticked, _unticked = enumerate_moc_sections_split(body_accepted)

    assert len(ticked) == 1, f"Expected 1 ticked cluster, got {len(ticked)}"
    cluster = ticked[0]

    assert "children" in cluster, f"Cluster dict must have 'children' key: {cluster.keys()}"
    children = cluster["children"]
    assert isinstance(children, list), f"children must be list, got {type(children)}"
    assert len(children) == 5, (
        f"Expected 5 children wikilinks, got {len(children)}: {children}"
    )
    # Each entry is the wikilink stem (not full [[...]] syntax)
    for i in range(5):
        assert f"child-{i}" in children, (
            f"Expected child-{i} in children list: {children}"
        )


def test_unticked_clusters_returned_separately_for_squelch() -> None:
    """Unticked clusters each carry a 'topic_signature' key for squelch persistence."""
    report = _empty_report()
    report["candidates"] = [_candidate(f"note-{i}") for i in range(3)]
    report["topic_clusters"] = [
        _cluster("MOC01", title="Squelch Alpha (MOC)", confidence=0.70,
                 candidate_stems=["note-0", "note-1"],
                 topic_keywords=["alpha", "topic"],
                 slug="squelch-alpha-moc"),
        _cluster("MOC02", title="Squelch Beta (MOC)", confidence=0.60,
                 candidate_stems=["note-2"],
                 topic_keywords=["beta"],
                 slug="squelch-beta-moc"),
    ]
    report["parent_options_per_cluster"] = {}

    _filename, body = render_moc_proposal_doc(report, _Cfg())
    # Leave all clusters un-ticked (no Accept box checked)

    ticked, unticked = enumerate_moc_sections_split(body)

    assert len(ticked) == 0, f"Expected 0 ticked, got {len(ticked)}"
    assert len(unticked) == 2, f"Expected 2 unticked, got {len(unticked)}"

    for cluster in unticked:
        assert "topic_signature" in cluster, (
            f"Unticked cluster must carry topic_signature for squelch: {cluster.keys()}"
        )
        sig = cluster["topic_signature"]
        assert isinstance(sig, str) and len(sig) > 0, (
            f"topic_signature must be a non-empty string, got {sig!r}"
        )


def test_filename_heuristic_fallback_still_works() -> None:
    """Backward-compat: no tomo: block, but filename matches tomo-moc-proposal-*.

    _is_moc_proposal_doc must still return True via the filename heuristic,
    even when the document has no tomo: block (old F-43 vault docs).
    """
    # Minimal body WITHOUT a tomo: block, but with MOC structure
    body_no_tomo_block = """\
---
type: tomo-proposal
proposal_kind: moc
created: 2026-01-01 00:00
status: pending
---

# MOC Proposal

### MOC01 — Legacy Topic (MOC)

- [ ] Accept
"""
    # Filename matches the old pattern
    result = _is_moc_proposal_doc(body_no_tomo_block, filename="tomo-moc-proposal-20260101-1200-legacy.md")
    assert result is True, (
        "Expected _is_moc_proposal_doc=True for filename-pattern match, "
        "even without tomo: block in frontmatter"
    )
