def test_skip_when_only_some_clusters_accepted() -> None:
    """Multi-cluster doc with 1 of 3 Accept ticked → returns exactly 1 ConfirmedMOCProposal."""
    report = _empty_report()
    report["candidates"] = [_candidate(f"note-{i}") for i in range(5)]
    report["topic_clusters"] = [
        _cluster("MOC01", title="Topic One (MOC)", confidence=0.80,
                 candidate_stems=["note-0", "note-1"], slug="topic-one-moc"),
        _cluster("MOC02", title="Topic Two (MOC)", confidence=0.65,
                 candidate_stems=["note-2", "note-3"], slug="topic-two-moc"),
        _cluster("MOC03", title="Topic Three (MOC)", confidence=0.50,
                 candidate_stems=["note-4"], slug="topic-three-moc"),
    ]
    report["parent_options_per_cluster"] = {}

    _filename, body = render_moc_proposal_doc(report, _Cfg())

    # Tick only the first Accept (MOC01 which is highest confidence, rendered first)
    # The rendered body has `- [ ] Accept` lines — tick only the first one
    first_accept_pos = body.index("- [ ] Accept")
    body_one_accepted = (
        body[:first_accept_pos]
        + "- [x] Accept"
        + body[first_accept_pos + len("- [ ] Accept"):]
    )

    results = parse_moc_proposal_doc(body_one_accepted, filename=_filename)

    assert len(results) == 1, (
        f"Expected 1 accepted proposal, got {len(results)}. "
        f"Results: {results}"
    )


