def _seed_discovery_cache(tmp_path: Path) -> Path:
    """Write a minimal discovery-cache.yaml covering several test clusters.

    Returns the path to the written file.

    Clusters covered:
    - Dataview cluster (tag:Obsidian/Plugin/Dataview, folder:Atlas/202 Notes/2611 Code Snippets/)
    - PKM cluster (free-text "map of content")
    - Class cluster (class:2600 → 2611 Code Snippets)
    """
    map_notes = [
        {
            "path": f"Atlas/200 Maps/{stem}.md",
            "title": stem,
            "discovered_via": "tag",
            "level": 1,
            "parent_moc": None,
            "child_mocs": [],
            "sibling_mocs": [],
            "state": None,
            "topics": ["obsidian", "plugin", "dataview", "tool"],
            "sections": [],
            "linked_notes": 2,
            "classification": "2600",
        }
        for stem in _CONCEPTS_MOC
    ] + [
        {
            "path": "Atlas/200 Maps/2600 - Applied Sciences.md",
            "title": "2600 - Applied Sciences",
            "discovered_via": "tag",
            "level": 0,
            "parent_moc": None,
            "child_mocs": [],
            "sibling_mocs": [],
            "state": None,
            "topics": ["applied sciences", "code", "dataview", "obsidian"],
            "sections": [],
            "linked_notes": 10,
            "classification": "2600",
        }
    ]

    # Atomic notes — Dataview cluster
    atomic_notes = [
        {
            "path": f"Atlas/202 Notes/2611 Code Snippets/{stem}.md",
            "title": stem,
            "tags": ["Obsidian/Plugin/Dataview"],
            "topics": ["dataview", "obsidian", "plugin", "query"],
            "classification": "2611",
        }
        for stem in _DATAVIEW_NOTES
    ] + [
        # PKM cluster notes (free-text / title mode)
        {
            "path": f"Atlas/202 Notes/{stem}.md",
            "title": stem,
            "tags": ["type/note/normal"],
            "topics": ["map of content", "moc", "pkm", "linking"],
            "classification": None,
        }
        for stem in ["Map of Content", "Map vs MOC", "Mapmaking", "Higher Order Notes", "Concepts"]
    ]

    # spec 021 T2.1: moc-discovery reads the MOC-structure cache via the loader,
    # which projects entries[kind=="moc"] → map_notes (shim). To preserve the
    # exact pre-wiring map_notes content these e2e tests were written against
    # (title/free-text read map_notes[].topics; Phase 6 dedups against it), the
    # whole pre-existing combined set (map_notes + atomic_notes) is written as
    # kind:moc entries so the shim surfaces it unchanged. A recent last_scan keeps
    # the cache FRESH so the loader loads it without a (Kado-needing) rebuild.
    from datetime import datetime, timezone

    fresh = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    entries = (
        [{**m, "kind": "moc"} for m in map_notes]
        + [{**a, "kind": "moc"} for a in atomic_notes]
    )
    cache = {
        "moc_cache_version": 1,
        "last_scan": fresh,
        "ttl_days": 1,
        "scope_paths": ["Atlas/200 Maps/", "Atlas/202 Notes/"],
        "exclude_paths": [],
        "moc_tag": "type/others/moc",
        "entries": entries,
        "placeholder_mocs": [],
    }

    cache_path = tmp_path / "moc-structure-cache.yaml"
    cache_path.write_text(yaml.dump(cache, allow_unicode=True), encoding="utf-8")
    return cache_path


