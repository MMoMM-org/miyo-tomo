def _candidate(
    stem: str,
    *,
    existing_up: str | None = None,
    existing_up_broken: bool = False,
    topics: list[str] | None = None,
    classification: str | None = None,
) -> dict:
    return {
        "stem": stem,
        "path": f"Atlas/202 Notes/{stem}.md",
        "topics": topics or [],
        "existing_up": existing_up,
        "existing_up_broken": existing_up_broken,
        "classification": classification,
        "level": 0,
    }


def _cluster(
    cluster_id: str,
    *,
    title: str,
    confidence: float,
    candidate_stems: list[str],
    topic_keywords: list[str] | None = None,
    slug: str | None = None,
    location: str = "Atlas/200 Maps/",
    template: str = "t_moc_tomo",
    existing_up: list[dict] | None = None,
) -> dict:
    return {
        "cluster_id": cluster_id,
        "title": title,
        "confidence": confidence,
        "candidate_stems": candidate_stems,
        "topic_keywords": topic_keywords or [],
        "slug": slug or title.lower().replace(" ", "-"),
        "location": location,
        "template": template,
        "existing_up": existing_up or [],
    }


def _empty_report() -> dict:
    return {
        "schema_version": "1",
        "run_id": "test-run-id",
        "mode": "tag",
        "trigger_arg": "topic/applied/test",
        "profile": "miyo",
        "candidates_total": 0,
        "candidates_after_prefilter": 0,
        "candidates_capped": False,
        "candidates": [],
        "topic_clusters": [],
        "parent_options_per_cluster": {},
        "duplicates_skipped": [],
        "squelched": [],
        "abort_reason": None,
        "abort_message": None,
        "extracted_via_llm_count": 0,
        "cache_miss_batches_used": 0,
    }


def _single_cluster_report() -> dict:
    """A minimal single-cluster DiscoveryReport."""
    report = _empty_report()
    report["candidates"] = [_candidate("note-a"), _candidate("note-b")]
    report["topic_clusters"] = [
        _cluster(
            "MOC01",
            title="Shell & Terminal (MOC)",
            confidence=0.78,
            candidate_stems=["note-a", "note-b"],
            slug="shell-terminal-moc",
        )
    ]
    report["parent_options_per_cluster"] = {
        "MOC01": [
            {
                "moc_stem": "2600 - Applied Sciences",
                "confidence": 0.85,
                "label": "Applied Sciences (Dewey 2600)",
            }
        ]
    }
    return report


