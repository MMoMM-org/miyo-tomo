# ── Report / cluster builder helpers ─────────────────────────────────────────

def make_candidate(
    stem: str,
    *,
    existing_up: str | None = None,
    existing_up_broken: bool = False,
    topics: list[str] | None = None,
    classification: str | None = None,
    folder: str = "Atlas/202 Notes/2611 Code Snippets/",
) -> dict:
    return {
        "stem": stem,
        "path": f"{folder}{stem}.md",
        "topics": topics or ["dataview", "obsidian", "plugin"],
        "existing_up": existing_up,
        "existing_up_broken": existing_up_broken,
        "classification": classification,
        "level": 0,
    }


def make_cluster(
    cluster_id: str,
    *,
    title: str,
    confidence: float,
    candidate_stems: list[str],
    topic_keywords: list[str] | None = None,
    slug: str | None = None,
    location: str = "Atlas/200 Maps/",
    template: str = "t_moc_tomo",
    existing_up: list[dict] | None = None,
    parent_options: list[dict] | None = None,
) -> tuple[dict, list[dict]]:
    """Return (cluster_dict, parent_options_list)."""
    cluster = {
        "cluster_id": cluster_id,
        "title": title,
        "confidence": confidence,
        "candidate_stems": candidate_stems,
        "topic_keywords": topic_keywords or ["dataview", "obsidian"],
        "slug": slug or title.lower().replace(" ", "-").replace("(", "").replace(")", ""),
        "location": location,
        "template": template,
        "existing_up": existing_up or [],
    }
    parents = parent_options or [
        {
            "moc_stem": "2600 - Applied Sciences",
            "confidence": 0.85,
            "label": "Applied Sciences (Dewey 2600)",
        }
    ]
    return cluster, parents


