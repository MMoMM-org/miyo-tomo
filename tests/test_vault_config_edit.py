#!/usr/bin/env python3
# version: 0.2.1
"""test_vault_config_edit.py — Behavioural tests for lib.vault_config_edit (spec 045 T2.1).

Covers the text-preserving nested-key editor behind `vault-config-writer.py review`:
- a scalar inserted four levels deep under existing parents, at the parents' indent
- a missing intermediate key and a missing top-level section created on the way
- replacing a scalar, a block list (by a flow list) and removing a key (null)
- a flow mapping on the key line rewritten as a block with the leaf merged: the
  key-line comment kept, every other member copied as written (nulls, plain and
  quoted scalars, floats, dates, nested flow mappings), a nested flow mapping
  descended into, a multi-line mapping handled, syntax the scan cannot rewrite
  refused with its own message, a mapping emptied by a removal written as `{}`
- a same-named key under another parent never touched; quoted keys found
- a scalar where a mapping is expected refused; CRLF endings kept
- every byte outside the edited lines identical (diff = insertions only)
"""
from __future__ import annotations

import difflib
import sys
from datetime import date
from pathlib import Path

import pytest
import yaml

SCRIPTS_DIR = Path(__file__).parent.parent / "tomo" / "scripts"
sys.path.insert(0, str(SCRIPTS_DIR))

from lib.vault_config_edit import EditRefused, get_path, set_path  # noqa: E402

CONFIG = """\
# Generated by install-tomo.sh
schema_version: 1

concepts:
  inbox: "100 Inbox/"

  calendar:
    base_path: "Calendar/"
    granularities:
      daily:
        enabled: true
        path: "Calendar/301 Daily/ "

  project: "Efforts/400 On/"

templates:
  base_path: "X/900 Support/930 Templater/"
  mapping:
    daily: "t_day_privat.md"
    # Optional: template for free-form artifacts
    # default: "Zettelkasten.md"
  note_include:
    - "t_*"

tomo:
  ttl_days: 1
"""


def _ops(before: str, after: str) -> set[str]:
    sm = difflib.SequenceMatcher(None, before.splitlines(True), after.splitlines(True))
    return {tag for tag, *_ in sm.get_opcodes()}


def test_inserts_scalar_four_levels_deep_at_sibling_indent():
    after = set_path(CONFIG, ("concepts", "calendar", "granularities", "weekly", "path"), "Calendar/302 Weekly/")
    assert _ops(CONFIG, after) == {"equal", "insert"}
    assert '\n      weekly:\n        path: "Calendar/302 Weekly/"\n' in after
    # Inserted after the daily block, before the blank line that precedes `project`.
    assert after.index('path: "Calendar/302 Weekly/"') < after.index("  project:")
    assert yaml.safe_load(after)["concepts"]["calendar"]["granularities"]["weekly"] == {"path": "Calendar/302 Weekly/"}
    assert yaml.safe_load(after)["concepts"]["calendar"]["granularities"]["daily"]["path"] == "Calendar/301 Daily/ "


def test_second_leaf_finds_the_block_the_first_created():
    after = set_path(CONFIG, ("concepts", "calendar", "granularities", "weekly", "enabled"), True)
    after = set_path(after, ("concepts", "calendar", "granularities", "weekly", "path"), "W/")
    assert after.count("weekly:") == 1
    assert '      weekly:\n        enabled: true\n        path: "W/"\n' in after
    assert _ops(CONFIG, after) == {"equal", "insert"}


def test_creates_missing_top_level_section_after_a_blank_line():
    after = set_path(CONFIG, ("review", "language"), "de")
    assert after.endswith('tomo:\n  ttl_days: 1\n\nreview:\n  language: "de"\n')
    assert after.startswith(CONFIG)
    after = set_path(after, ("review", "week", "first_day"), "monday")
    after = set_path(after, ("review", "week", "min_days_in_first_week"), 4)
    assert after.endswith('review:\n  language: "de"\n  week:\n    first_day: "monday"\n    min_days_in_first_week: 4\n')


def test_creates_missing_section_and_two_levels_in_one_call():
    after = set_path(CONFIG, ("naming", "calendar_patterns", "weekly"), "GGGG-[W]WW")
    assert after.endswith('\nnaming:\n  calendar_patterns:\n    weekly: "GGGG-[W]WW"\n')
    assert yaml.safe_load(after)["naming"] == {"calendar_patterns": {"weekly": "GGGG-[W]WW"}}


def test_replaces_scalar_in_place_keeping_neighbours():
    after = set_path(CONFIG, ("concepts", "calendar", "granularities", "daily", "path"), "Calendar/301 Daily/")
    assert after == CONFIG.replace('path: "Calendar/301 Daily/ "', 'path: "Calendar/301 Daily/"')


def test_inserts_under_mapping_whose_last_lines_are_comments():
    after = set_path(CONFIG, ("templates", "mapping", "weekly"), "t_week.md")
    assert '    # default: "Zettelkasten.md"\n    weekly: "t_week.md"\n  note_include:' in after
    assert _ops(CONFIG, after) == {"equal", "insert"}


def test_replaces_block_list_with_flow_list_and_removes_key_on_null():
    after = set_path(CONFIG, ("templates", "note_include"), ["a.md", "b.md"])
    assert '  note_include: ["a.md", "b.md"]\n\ntomo:' in after
    assert '- "t_*"' not in after
    removed = set_path(after, ("templates", "note_include"), None)
    assert "note_include" not in removed
    assert yaml.safe_load(removed)["templates"] == {
        "base_path": "X/900 Support/930 Templater/", "mapping": {"daily": "t_day_privat.md"},
    }
    assert set_path(CONFIG, ("templates", "mapping", "weekly"), None) == CONFIG


def test_flow_mapping_on_key_line_is_rewritten_as_block():
    config = (
        "concepts:\n  calendar:\n    granularities:\n"
        '      daily:     { enabled: true,  path: "D/" }\n'
        '      weekly:    { enabled: true, path: "W/" }\n'
        '      monthly:   { enabled: true, path: "M/" }\n'
        "other: 1\n"
    )
    after = set_path(config, ("concepts", "calendar", "granularities", "weekly", "path"), "New W/")
    assert '      weekly:\n        enabled: true\n        path: "New W/"\n' in after
    assert '      daily:     { enabled: true,  path: "D/" }\n' in after
    assert '      monthly:   { enabled: true, path: "M/" }\n' in after
    assert yaml.safe_load(after)["concepts"]["calendar"]["granularities"]["weekly"] == {"enabled": True, "path": "New W/"}


FLOW = (
    "granularities:\n"
    "  weekly: { enabled: true, path: W/, template: ~, legacy: null, since: 2026-01-05,"
    " ratio: 0.5, tags: [a, 'b c'], nested: { x: 1 } }  # from the profile\n"
    "other: 1\n"
)

FLOW_BLOCK_HEAD = "granularities:\n  weekly:  # from the profile\n    enabled: true\n"
FLOW_BLOCK_TAIL = (
    "    template: ~\n    legacy: null\n    since: 2026-01-05\n    ratio: 0.5\n"
    "    tags: [a, 'b c']\n    nested: { x: 1 }\nother: 1\n"
)


def test_flow_mapping_rewrite_keeps_the_key_line_comment():
    after = set_path(FLOW, ("granularities", "weekly", "path"), "New W/")
    assert after.startswith("granularities:\n  weekly:  # from the profile\n")
    assert after.count("# from the profile") == 1


def test_flow_mapping_rewrite_keeps_null_members_as_written():
    after = set_path(FLOW, ("granularities", "weekly", "path"), "New W/")
    assert "    template: ~\n    legacy: null\n" in after
    parsed = yaml.safe_load(after)["granularities"]["weekly"]
    assert parsed["template"] is None and parsed["legacy"] is None and "template" in parsed


def test_flow_mapping_rewrite_keeps_sibling_spelling_and_scalar_types():
    after = set_path(FLOW, ("granularities", "weekly", "path"), "New W/")
    assert after == FLOW_BLOCK_HEAD + '    path: "New W/"\n' + FLOW_BLOCK_TAIL
    parsed = yaml.safe_load(after)["granularities"]["weekly"]
    assert parsed["since"] == date(2026, 1, 5) and parsed["ratio"] == 0.5
    assert parsed["tags"] == ["a", "b c"] and parsed["nested"] == {"x": 1}


def test_flow_mapping_rewrite_only_re_renders_the_edited_leaf():
    # The leaf gets the module's rendering; nothing else is re-rendered.
    config = "weekly: { enabled: true, path: W/ }\n"
    assert set_path(config, ("weekly", "path"), "W/") == 'weekly:\n  enabled: true\n  path: "W/"\n'
    assert set_path(config, ("weekly", "enabled"), False) == "weekly:\n  enabled: false\n  path: W/\n"


def test_flow_mapping_leaf_removed_added_and_bare_member_kept():
    config = "weekly: { enabled: true, note, path: W/ }\n"
    assert set_path(config, ("weekly", "path"), None) == "weekly:\n  enabled: true\n  note:\n"
    assert set_path(config, ("weekly", "heading"), "H") == 'weekly:\n  enabled: true\n  note:\n  path: W/\n  heading: "H"\n'
    assert set_path(config, ("weekly", "missing"), None) == config


def test_removing_the_only_flow_member_leaves_an_empty_mapping_not_a_null():
    # `weekly:` alone reads back as null; the key stayed a mapping, so it is written as `{}`.
    assert set_path("weekly: { path: W/ }\n", ("weekly", "path"), None) == "weekly: {}\n"
    after = set_path("weekly: { path: W/ }  # c\nother: 1\n", ("weekly", "path"), None)
    assert after == "weekly: {}  # c\nother: 1\n"
    assert yaml.safe_load(after)["weekly"] == {}
    nested = set_path("calendar: { granularities: { weekly: { path: W/ } } }\n",
                      ("calendar", "granularities", "weekly", "path"), None)
    assert nested == "calendar:\n  granularities:\n    weekly: {}\n"
    assert yaml.safe_load(nested)["calendar"]["granularities"]["weekly"] == {}


def test_flow_mapping_quoted_key_line_and_quoted_member_keys_keep_their_quotes():
    config = '"weekly": { "enabled": true, \'path\': W/ }\n'
    after = set_path(config, ("weekly", "path"), "X/")
    assert after == '"weekly":\n  "enabled": true\n  \'path\': "X/"\n'
    assert yaml.safe_load(after) == {"weekly": {"enabled": True, "path": "X/"}}


def test_flow_mapping_descends_into_a_nested_flow_mapping_and_creates_missing_levels():
    config = "calendar: { base: C/, granularities: { weekly: { enabled: true, path: W/ } } }  # c\n"
    after = set_path(config, ("calendar", "granularities", "weekly", "path"), "X/")
    assert after == (
        "calendar:  # c\n  base: C/\n  granularities:\n    weekly:\n      enabled: true\n      path: \"X/\"\n"
    )
    after = set_path(config, ("calendar", "granularities", "monthly", "path"), "M/")
    assert after == (
        "calendar:  # c\n  base: C/\n  granularities:\n    weekly: { enabled: true, path: W/ }\n"
        "    monthly:\n      path: \"M/\"\n"
    )
    after = set_path("calendar: { granularities: ~ }\n", ("calendar", "granularities", "weekly", "path"), "W/")
    assert after == 'calendar:\n  granularities:\n    weekly:\n      path: "W/"\n'


def test_multi_line_flow_mapping_is_rewritten_with_members_on_their_own_lines():
    config = "weekly: {\n    enabled: true,  # inside\n    path: W/,\n  }\nother: 1\n"
    after = set_path(config, ("weekly", "heading"), "H")
    assert after == 'weekly:\n  enabled: true\n  path: W/\n  heading: "H"\nother: 1\n'


def test_scalar_inside_a_flow_mapping_where_a_mapping_is_expected_is_refused():
    with pytest.raises(EditRefused, match="scalar"):
        set_path("calendar: { granularities: plain }\n", ("calendar", "granularities", "weekly"), "x")
    with pytest.raises(EditRefused, match="scalar"):
        set_path("calendar: [a, b]\n", ("calendar", "weekly"), "x")


@pytest.mark.parametrize("config", [
    "weekly: { ? enabled : true, path: W/ }\n",   # explicit key: the scan and YAML disagree
    "weekly: { path: A/, path: B/ }\n",           # duplicate member
    "weekly: { true: 1 }\n",                      # typed key
    "weekly: { path: W/ \n",                      # unbalanced
    "weekly: { path: W/ } junk\n",                # text after the closing brace
])
def test_flow_mapping_the_scan_cannot_rewrite_is_refused_with_its_own_message(config):
    with pytest.raises(EditRefused, match="could not be rewritten as a block"):
        set_path(config, ("weekly", "heading"), "H")


def test_same_named_key_under_another_parent_is_not_touched():
    config = "review:\n  weekly:\n    heading: \"A\"\nconcepts:\n  calendar:\n    granularities:\n      weekly:\n        path: \"W/\"\n"
    after = set_path(config, ("review", "weekly", "heading"), "B")
    assert after == config.replace('heading: "A"', 'heading: "B"')
    assert 'path: "W/"' in after


def test_quoted_key_is_the_same_key():
    config = 'review:\n  "language": de\n  week:\n    first_day: monday\n'
    after = set_path(config, ("review", "language"), "en")
    assert after == 'review:\n  language: "en"\n  week:\n    first_day: monday\n'


def test_scalar_where_mapping_expected_is_refused():
    config = "review:\n  weekly: plain\n"
    with pytest.raises(EditRefused):
        set_path(config, ("review", "weekly", "heading"), "X")


def test_crlf_file_gets_crlf_insertions():
    config = "review:\r\n  language: de\r\nother: 1\r\n"
    after = set_path(config, ("review", "weekly", "heading"), "Tomo Review")
    assert after == 'review:\r\n  language: de\r\n  weekly:\r\n    heading: "Tomo Review"\r\nother: 1\r\n'


def test_missing_trailing_newline_is_repaired_before_append():
    after = set_path("a: 1", ("review", "language"), "de")
    assert after == 'a: 1\n\nreview:\n  language: "de"\n'


def test_get_path():
    data = yaml.safe_load(CONFIG)
    assert get_path(data, ("concepts", "calendar", "granularities", "daily", "path")) == (True, "Calendar/301 Daily/ ")
    assert get_path(data, ("concepts", "calendar", "granularities", "weekly", "path")) == (False, None)
    assert get_path(data, ("concepts", "inbox", "deeper")) == (False, None)
