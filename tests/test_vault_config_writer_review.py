#!/usr/bin/env python3
# version: 0.1.0
"""test_vault_config_writer_review.py — `vault-config-writer.py review` (spec 045 T2.1, ADR-5).

Runs the subcommand as a subprocess on a synthetic config shaped like the
instance's (block-style calendar with only a daily granularity whose path has a
trailing space, a hand-curated templates block, trackers, a tomo section at the
end; no naming or review section) and, when present, on a copy of
tomo-instance/config/vault-config.yaml (never the instance file itself). Covers:
- a week setup written: absent nested keys inserted four levels deep, missing
  naming: and review: sections created, the diff against the original is
  insertions only (every other byte unchanged)
- the same input again is `unchanged` and the file is byte-identical
- a month setup lands beside the week setup
- the daily path is fixed only when the input says so
- schema violations and an unusable format are `refused` with pointers, nothing written
- a duplicate key the edit would introduce and a pre-existing duplicate in a
  touched section are refused, nothing written
- a null template removes the mapping key; stdout names keys, never values
- missing config exits 2
"""
from __future__ import annotations

import difflib
import json
import subprocess
import sys
from pathlib import Path

import pytest
import yaml

TESTS_DIR = Path(__file__).resolve().parent
REPO_ROOT = TESTS_DIR.parent
WRITER = REPO_ROOT / "tomo" / "scripts" / "vault-config-writer.py"
INSTANCE_CONFIG = REPO_ROOT / "tomo-instance" / "config" / "vault-config.yaml"

CONFIG = """\
# Generated by install-tomo.sh on 2026-04-20
# version: 0.2.0
schema_version: 1

profile: "miyo"

concepts:
  inbox: "100 Inbox/"

  atomic_note:
    # M8: `path` (not `base_path`) so moc_scan picks up the scope.
    path: "Atlas/202 Notes/"

  calendar:
    base_path: "Calendar/"
    granularities:
      daily:
        enabled: true
        path: "Calendar/301 Daily/ "

  project: "Efforts/400 On/"

templates:
  base_path: "X/900 Support/930 Templater/"
  mapping:
    atomic_note: "t_note_tomo.md"
    daily: "t_day_privat.md"
  note_include:
    - "t_*"

trackers:
  daily_note_trackers:
    section: "Habit"
    today_fields:
      - name: "Sleep"
        type: "text"
        syntax: "inline_field"
        description: "Detected from daily template."
        positive_keywords: ["geschlafen", "Schlaf"]

tomo:
  # MOC-structure cache scope/TTL (spec 021).
  moc_structure_cache:
    exclude_paths:
      - "Calendar/301 Daily/ "
    ttl_days: 1
"""

WEEK = {
    "kind": "week", "folder": "Calendar/302 Weekly/", "format": "GGGG-[W]WW",
    "first_day": "monday", "min_days": 4, "template": "t_week_privat.md", "template_variant": None,
    "heading": "Tomo Review", "place": {"anchor": "In my own words", "placement": "before"},
    "own_sections": ["In my own words", "Reflections"],
    "daily_sections": ["Habit", "5 Year Journal", "Daily Log"], "skip_sections": ["On This Day... last year"],
    "task_notes": ["Efforts/500 OnGoing/Next Todos.md"], "max_chars_per_day": 12000, "language": "de",
}

MONTH = {
    "kind": "month", "folder": "Calendar/303 Monthly/", "format": "YYYY-MM", "template": "t_month_privat.md",
    "heading": "Tomo Review", "place": {"anchor": "In my own words", "placement": "before"},
    "own_sections": ["In my own words", "Reflections"], "language": "de",
}

SECRET = "zqx_secret_marker"


def _run(tmp_path: Path, config_text, payload, *extra):
    cfg = tmp_path / "vault-config.yaml"
    if isinstance(config_text, bytes):
        cfg.write_bytes(config_text)
    elif config_text is not None:
        cfg.write_text(config_text, encoding="utf-8")
    inp = tmp_path / "review.json"
    inp.write_text(json.dumps(payload) if not isinstance(payload, str) else payload, encoding="utf-8")
    proc = subprocess.run(
        [sys.executable, str(WRITER), "review", "--input", str(inp), "--config", str(cfg), *extra],
        capture_output=True, text=True, timeout=60,
    )
    return proc, cfg


def _out(proc) -> dict:
    assert proc.returncode == 0, proc.stderr
    return json.loads(proc.stdout)


def _diff_tags(before: str, after: str) -> set[str]:
    sm = difflib.SequenceMatcher(None, before.splitlines(True), after.splitlines(True))
    return {tag for tag, *_ in sm.get_opcodes()}


def _assert_week_written(before: str, after: str) -> None:
    assert _diff_tags(before, after) == {"equal", "insert"}, "the edit must only insert lines"
    parsed = yaml.safe_load(after)
    gran = parsed["concepts"]["calendar"]["granularities"]
    assert gran["weekly"] == {"enabled": True, "path": "Calendar/302 Weekly/"}
    assert gran["daily"]["path"] == "Calendar/301 Daily/ ", "the daily path is not fixed unless asked"
    assert parsed["naming"]["calendar_patterns"] == {"weekly": "GGGG-[W]WW"}
    assert parsed["templates"]["mapping"]["weekly"] == "t_week_privat.md"
    assert parsed["review"] == {
        "language": "de",
        "week": {"first_day": "monday", "min_days_in_first_week": 4},
        "daily": {"sections": ["Habit", "5 Year Journal", "Daily Log"], "skip_sections": ["On This Day... last year"],
                  "task_notes": ["Efforts/500 OnGoing/Next Todos.md"], "max_chars_per_day": 12000},
        "weekly": {"heading": "Tomo Review", "place": {"anchor": "In my own words", "placement": "before"},
                   "own_sections": ["In my own words", "Reflections"]},
    }
    # granularities, naming, templates.mapping and review each hold one weekly key
    assert after.count("weekly:") == 4 and after.count("review:") == 1 and after.count("naming:") == 1


def test_week_setup_inserts_nested_keys_and_creates_sections(tmp_path):
    proc, cfg = _run(tmp_path, CONFIG, WEEK)
    out = _out(proc)
    assert out["status"] == "written"
    assert "review.weekly.heading" in out["keys"] and "concepts.calendar.granularities.weekly.path" in out["keys"]
    assert "Calendar/302 Weekly/" not in proc.stdout and "Tomo Review" not in proc.stdout
    after = cfg.read_text(encoding="utf-8")
    _assert_week_written(CONFIG, after)
    # The granularity sits under the existing daily block, at its indent.
    assert '        path: "Calendar/301 Daily/ "\n      weekly:\n        enabled: true\n        path: "Calendar/302 Weekly/"\n\n  project:' in after
    assert '    daily: "t_day_privat.md"\n    weekly: "t_week_privat.md"\n  note_include:' in after


@pytest.mark.skipif(not INSTANCE_CONFIG.exists(), reason="no tomo-instance config on this host")
def test_week_setup_on_a_copy_of_the_instance_config(tmp_path):
    original = INSTANCE_CONFIG.read_bytes()
    proc, cfg = _run(tmp_path, original, WEEK)
    assert _out(proc)["status"] == "written"
    after = cfg.read_text(encoding="utf-8")
    _assert_week_written(original.decode("utf-8"), after)
    assert INSTANCE_CONFIG.read_bytes() == original


def test_same_input_again_is_unchanged_and_byte_identical(tmp_path):
    proc, cfg = _run(tmp_path, CONFIG, WEEK)
    assert _out(proc)["status"] == "written"
    written = cfg.read_bytes()
    proc, cfg = _run(tmp_path, None, WEEK)
    assert _out(proc) == {"status": "unchanged"}
    assert cfg.read_bytes() == written


def test_month_setup_lands_beside_the_week_setup(tmp_path):
    _run(tmp_path, CONFIG, WEEK)
    after_week = (tmp_path / "vault-config.yaml").read_text(encoding="utf-8")
    proc, cfg = _run(tmp_path, None, MONTH)
    assert _out(proc)["status"] == "written"
    after = cfg.read_text(encoding="utf-8")
    assert _diff_tags(after_week, after) == {"equal", "insert"}
    parsed = yaml.safe_load(after)
    assert parsed["concepts"]["calendar"]["granularities"]["monthly"] == {"enabled": True, "path": "Calendar/303 Monthly/"}
    assert parsed["naming"]["calendar_patterns"] == {"weekly": "GGGG-[W]WW", "monthly": "YYYY-MM"}
    assert parsed["review"]["week"] == {"first_day": "monday", "min_days_in_first_week": 4}
    assert parsed["review"]["monthly"]["place"] == {"anchor": "In my own words", "placement": "before"}
    assert parsed["review"]["weekly"]["heading"] == "Tomo Review"


def test_daily_path_fixed_only_when_the_input_says_so(tmp_path):
    proc, cfg = _run(tmp_path, CONFIG, dict(WEEK, daily_path_fix="Calendar/301 Daily/"))
    out = _out(proc)
    assert "concepts.calendar.granularities.daily.path" in out["keys"]
    after = cfg.read_text(encoding="utf-8")
    assert '        path: "Calendar/301 Daily/"\n' in after
    assert 'path: "Calendar/301 Daily/ "' not in after
    assert '      - "Calendar/301 Daily/ "\n' in after, "the tomo: exclude path is not the daily path key"
    assert _diff_tags(CONFIG, after) == {"equal", "insert", "replace"}


def test_changed_value_replaces_the_line_only(tmp_path):
    _run(tmp_path, CONFIG, WEEK)
    before = (tmp_path / "vault-config.yaml").read_text(encoding="utf-8")
    proc, cfg = _run(tmp_path, None, dict(WEEK, heading="Rückblick", own_sections=["Reflections"]))
    out = _out(proc)
    assert out["status"] == "written" and sorted(out["keys"]) == ["review.weekly.heading", "review.weekly.own_sections"]
    after = cfg.read_text(encoding="utf-8")
    assert _diff_tags(before, after) == {"equal", "replace"}
    assert yaml.safe_load(after)["review"]["weekly"]["heading"] == "Rückblick"


def test_null_template_removes_the_mapping_key(tmp_path):
    _run(tmp_path, CONFIG, WEEK)
    proc, cfg = _run(tmp_path, None, dict(WEEK, template=None))
    assert _out(proc)["keys"] == ["templates.mapping.weekly"]
    after = cfg.read_text(encoding="utf-8")
    assert "t_week_privat.md" not in after
    assert yaml.safe_load(after)["templates"]["mapping"] == {"atomic_note": "t_note_tomo.md", "daily": "t_day_privat.md"}


@pytest.mark.parametrize("payload, pointer", [
    (dict(WEEK, place={"anchor": "In my own words", "placement": "after"}), "/place/placement"),
    ({k: v for k, v in WEEK.items() if k != "kind"}, "/"),
    (dict(MONTH, first_day="monday"), "/first_day"),
    (dict(WEEK, bogus=1), "/"),
    (dict(WEEK, folder=" Calendar/302 Weekly/"), "/folder"),
    (dict(WEEK, language="Deutsch"), "/language"),
    (dict(WEEK, format="YYYY-[W]WW"), "/format"),
    (dict(WEEK, format="GGGG/[W]WW"), "/format"),
    (dict(WEEK, first_day="sunday", format="GGGG-[W]WW"), "/format"),
])
def test_invalid_input_is_refused_with_pointers_and_nothing_written(tmp_path, payload, pointer):
    proc, cfg = _run(tmp_path, CONFIG, payload)
    out = _out(proc)
    assert out["status"] == "refused" and pointer in out["pointers"], out
    assert cfg.read_text(encoding="utf-8") == CONFIG
    assert "Weekly" not in proc.stdout + proc.stderr


def test_invalid_json_input_is_refused(tmp_path):
    proc, cfg = _run(tmp_path, CONFIG, "{not json")
    assert _out(proc)["status"] == "refused"
    assert cfg.read_text(encoding="utf-8") == CONFIG


def test_preexisting_duplicate_in_a_touched_section_is_refused(tmp_path):
    config = CONFIG + f"\nreview:\n  language: {SECRET}\nreview:\n  language: x\n"
    proc, cfg = _run(tmp_path, config, WEEK)
    out = _out(proc)
    assert out["status"] == "refused" and "pre-existing" in out["reason"], out
    assert cfg.read_text(encoding="utf-8") == config
    assert SECRET not in proc.stdout + proc.stderr


def test_duplicate_the_edit_introduces_is_refused(tmp_path):
    # `language :` is not recognised as the key, so the edit would add a second one.
    config = CONFIG + f"\nreview:\n  language : {SECRET}\n"
    proc, cfg = _run(tmp_path, config, WEEK)
    out = _out(proc)
    assert out["status"] == "refused" and "introduced by the edit" in out["reason"], out
    assert cfg.read_text(encoding="utf-8") == config
    assert SECRET not in proc.stdout + proc.stderr


def test_duplicate_in_an_untouched_section_is_left_alone(tmp_path):
    config = CONFIG + f"\nother:\n  {SECRET}: 1\n  {SECRET}: 2\n"
    proc, cfg = _run(tmp_path, config, WEEK)
    assert _out(proc)["status"] == "written"
    assert SECRET not in proc.stdout + proc.stderr


def test_scalar_where_a_mapping_is_expected_is_refused(tmp_path):
    config = CONFIG + "\nreview:\n  weekly: plain\n"
    proc, cfg = _run(tmp_path, config, WEEK)
    out = _out(proc)
    assert out["status"] == "refused", out
    assert cfg.read_text(encoding="utf-8") == config


def test_flow_granularity_from_the_profile_is_rewritten_in_place(tmp_path):
    config = CONFIG.replace(
        '      daily:\n        enabled: true\n        path: "Calendar/301 Daily/ "\n',
        '      daily:     { enabled: true,  path: "Calendar/301 Daily/" }\n'
        '      weekly:    { enabled: true, path: "Calendar/302 Weekly/" }\n',
    )
    proc, cfg = _run(tmp_path, config, dict(WEEK, folder="Weeks/"))
    assert _out(proc)["status"] == "written"
    after = cfg.read_text(encoding="utf-8")
    assert '      daily:     { enabled: true,  path: "Calendar/301 Daily/" }\n' in after
    assert yaml.safe_load(after)["concepts"]["calendar"]["granularities"]["weekly"] == {"enabled": True, "path": "Weeks/"}


def test_crlf_config_keeps_crlf(tmp_path):
    config = CONFIG.replace("\n", "\r\n").encode("utf-8")
    proc, cfg = _run(tmp_path, config, WEEK)
    assert _out(proc)["status"] == "written"
    after = cfg.read_bytes()
    assert b"\n" not in after.replace(b"\r\n", b""), "line endings mixed"
    assert yaml.safe_load(after)["review"]["weekly"]["heading"] == "Tomo Review"


def test_broken_config_is_refused_without_config_text(tmp_path):
    config = CONFIG + f"\nbroken: [{SECRET}\n"
    proc, cfg = _run(tmp_path, config, WEEK)
    out = _out(proc)
    assert out["status"] == "refused" and "line" in out["reason"], out
    assert SECRET not in proc.stdout + proc.stderr
    assert cfg.read_text(encoding="utf-8") == config


def test_missing_config_exits_2(tmp_path):
    proc, cfg = _run(tmp_path, None, WEEK)
    assert proc.returncode == 2 and not cfg.exists()


def test_missing_input_exits_2(tmp_path):
    cfg = tmp_path / "vault-config.yaml"
    cfg.write_text(CONFIG, encoding="utf-8")
    proc = subprocess.run(
        [sys.executable, str(WRITER), "review", "--input", str(tmp_path / "none.json"), "--config", str(cfg)],
        capture_output=True, text=True, timeout=60,
    )
    assert proc.returncode == 2
